"""
engine_examples.py
==================
Example exports of a Strategy Studio tree for other decisioning engines.

These are ILLUSTRATIVE hand-off artefacts that show how a Dataiku strategy maps onto each
engine's concepts; they are not official vendor import formats (except DMN 1.3, which is an
OMG standard). Strategy Studio works without this module: ``strategy_engine`` picks it up
if it imports, and ignores it otherwise.

Every format is built from the same flattening: one rule per leaf, whose conditions are the
splits on the path to the leaf (mutually exclusive, so first-hit and unique-hit agree).

  oscilar   Oscilar risk decisioning – workflow with ordered rules and actions (JSON)
  pega      Pega Customer Decision Hub – decision table rule (JSON)
  provenir  Provenir decisioning platform – decision tree component (JSON)
  taktile   Taktile – decision flow with a decision table and Python assignments (JSON)
  dmn       DMN 1.3 decision table (XML, FEEL) – Camunda, Trisotech, Red Hat, IBM ODM…
"""

import hashlib
import json
from xml.sax.saxutils import escape

import strategy_engine as se

NOTE = ("Illustrative {engine}-style export generated by Dataiku Strategy Studio for demonstration "
        "purposes; element names are not an official {vendor} specification. Map the inputs to the "
        "engine's data model before import.")

FORMATS = {
    "oscilar": ("Oscilar workflow rules (example)", "json"),
    "pega": ("Pega decision table (example)", "json"),
    "provenir": ("Provenir decision tree (example)", "json"),
    "taktile": ("Taktile decision flow (example)", "json"),
    "dmn": ("DMN 1.3 decision table (standard XML)", "dmn"),
}


# ── shared flattening ───────────────────────────────────────────────────────

def rules(tree):
    """[(leaf, [(split, branch), ...])] in tree order."""
    out = []
    for n, _, path in se.walk(tree):
        if n["type"] == "leaf":
            out.append((n, list(path)))
    return out


def actions(leaf):
    """Engine-neutral leaf actions."""
    a = leaf.get("score_adjust") or {}
    t, v = a.get("type", "none"), se._num(a.get("value"))
    d = leaf.get("decision") or {}
    lm = se._num(leaf.get("limit_multiplier"))
    return dict(adjust=(t if v is not None else "none", v), mode=d.get("mode", "cutoff"),
                approve_at=se._num(d.get("approve_at")), refer_at=se._num(d.get("refer_at")),
                reason_codes=list(leaf.get("reason_codes") or []), pricing_tier=leaf.get("pricing_tier") or "",
                limit_multiplier=1.0 if lm is None else lm)


class Dialect:
    """Expression syntax of one engine. Missing-value routing follows Strategy Studio."""
    AND, OR, NOT = " and ", " or ", "not ({})"
    TRUE = "true"

    def ref(self, var):
        return var

    def lit(self, v):
        f = se._num(v)
        if f is not None:
            return repr(int(f)) if float(f).is_integer() else repr(f)
        return '"' + str(v).replace('"', '\\"') + '"'

    def is_null(self, x):
        return f"{x} == null"

    def not_null(self, x):
        return f"{x} != null"

    def in_list(self, x, vals):
        return "(" + self.OR.join(f"{x} == {self.lit(v)}" for v in vals) + ")"

    def cmp(self, x, op, v):
        return f"{x} {op} {self.lit(v)}"

    def cond(self, n):
        x, op = self.ref(n["variable"]), n["op"]
        if op == "is_missing":
            return self.is_null(x)
        if op == "between":
            return f"({self.cmp(x, '>=', n['value'])}{self.AND}{self.cmp(x, '<=', n['value2'])})"
        if op in ("in", "not_in"):
            c = self.in_list(x, se._list(n["value"]))
            return c if op == "in" else self.NOT.format(c)
        return self.cmp(x, op, n["value"])

    def branch(self, n, branch):
        x, c = self.ref(n["variable"]), self.cond(n)
        if n["op"] == "is_missing":
            return c if branch == "yes" else self.not_null(x)
        miss_yes = n.get("missing") == "yes"
        if branch == "yes":
            return (f"({self.is_null(x)}{self.OR}{c})" if miss_yes else f"({self.not_null(x)}{self.AND}{c})")
        neg = self.NOT.format(c)
        return (f"({self.not_null(x)}{self.AND}{neg})" if miss_yes else f"({self.is_null(x)}{self.OR}{neg})")

    def when(self, path):
        return self.AND.join(self.branch(s, b) for s, b in path) or self.TRUE

    def score(self, score_ref, act):
        t, v = act["adjust"]
        if t == "pct":
            return f"{score_ref} * {1 + v / 100.0:.12g}"
        if t == "points":
            return f"{score_ref} + ({v:.12g})"
        if t == "set":
            return f"{v:.12g}"
        return score_ref

    def decision(self, adj_ref, act):
        if act["mode"] != "cutoff":
            return self.lit(act["mode"].upper())
        out = self.lit("DECLINE")
        if act["refer_at"] is not None:
            out = self.ifelse(f"{adj_ref} >= {act['refer_at']:.12g}", self.lit("REFER"), out)
        out = self.ifelse(f"{adj_ref} >= {act['approve_at']:.12g}", self.lit("APPROVE"), out)
        return self.ifelse(self.is_null(adj_ref), self.lit("REFER"), out)

    def ifelse(self, c, a, b):
        return f"({c} ? {a} : {b})"


class JS(Dialect):          # Oscilar-style expressions
    AND, OR, NOT = " && ", " || ", "!({})"

    def in_list(self, x, vals):
        return f"[{', '.join(self.lit(v) for v in vals)}].includes(String({x}))"

    def lit(self, v):
        return json.dumps(str(v)) if se._num(v) is None else super().lit(v)


class Pega(Dialect):        # Pega expression builder style: .Property, @isBlank
    AND, OR, NOT = " && ", " || ", "!({})"

    def ref(self, var):
        return "." + "".join(p.capitalize() for p in var.split("_"))

    def is_null(self, x):
        return f"@isBlank({x})"

    def not_null(self, x):
        return f"!@isBlank({x})"

    def ifelse(self, c, a, b):
        return f"@if({c}, {a}, {b})"


class Py(Dialect):          # Taktile code / assignment nodes are Python
    TRUE = "True"

    def ref(self, var):
        return f"data.{var}" if var.isidentifier() else f"data[{var!r}]"

    def is_null(self, x):
        return f"{x} is None"

    def not_null(self, x):
        return f"{x} is not None"

    def in_list(self, x, vals):
        return f"str({x}) in {[str(v) for v in vals]!r}"

    def ifelse(self, c, a, b):
        return f"({a} if {c} else {b})"


class Feel(Dialect):        # DMN FEEL
    AND, OR, NOT = " and ", " or ", "not({})"

    def ref(self, var):
        return var

    def is_null(self, x):
        return f"{x} = null"

    def not_null(self, x):
        return f"{x} != null"

    def cmp(self, x, op, v):
        return f"{x} {'=' if op == '==' else op} {self.lit(v)}"

    def in_list(self, x, vals):
        return f"list contains([{', '.join(self.lit(v) for v in vals)}], string({x}))"

    def lit(self, v):
        return json.dumps(str(v)) if se._num(v) is None else super().lit(v)

    def ifelse(self, c, a, b):
        return f"if {c} then {a} else {b}"


def _header(engine, vendor, meta, artifact):
    return {"schemaNote": NOTE.format(engine=engine, vendor=vendor), "artifactType": artifact,
            "targetPlatform": engine, "schemaVersion": "1.0-example",
            "strategy": {"strategyId": meta.get("strategy_id"), "name": meta.get("name"),
                         "version": meta.get("version", 1), "status": meta.get("status", "DRAFT"),
                         "scoreField": meta.get("score_col", "score"), "source": "Dataiku Strategy Studio",
                         "project": meta.get("project", ""), "dataset": meta.get("dataset", "")}}


def _inputs(tree, meta, column_types):
    score = meta.get("score_col", "score")
    return [{"name": v, "type": "number" if (column_types or {}).get(v) == "numeric" else "string",
             "source": se.input_source(v, score)}
            for v in [score] + [x for x in se.variables_used(tree) if x != score]]


def _finish(doc, backtest_summary):
    body = {k: v for k, v in doc.items() if k not in ("schemaNote",)}
    doc["backtest"] = backtest_summary or {}
    doc["governance"] = {"checksum": "sha256:" + hashlib.sha256(json.dumps(body, sort_keys=True, default=str)
                                                                .encode()).hexdigest(),
                         "generatedAt": se._now(), "generatedBy": "Dataiku Strategy Studio"}
    return doc


# ── engines ─────────────────────────────────────────────────────────────────

def to_oscilar(tree, meta, column_types=None, backtest_summary=None):
    d, score = JS(), meta.get("score_col", "score")
    doc = _header("Oscilar", "Oscilar", meta, "OSCILAR_WORKFLOW")
    doc["inputs"] = _inputs(tree, meta, column_types)
    doc["workflow"] = {
        "name": meta.get("name"), "evaluation": "FIRST_MATCH",
        "steps": [{"stepId": "strategy_rules", "type": "RULE_SET", "rules": [
            {"ruleId": lf["id"], "name": lf.get("name") or lf["id"], "priority": i + 1,
             "condition": d.when(path),
             "actions": [
                 {"type": "SET_VARIABLE", "variable": "adjusted_score", "expression": d.score(score, a)},
                 {"type": "SET_DECISION", "expression": d.decision("adjusted_score", a)},
                 {"type": "ADD_REASON_CODES", "values": a["reason_codes"]},
                 {"type": "SET_VARIABLE", "variable": "pricing_tier", "value": a["pricing_tier"]},
                 {"type": "SET_VARIABLE", "variable": "limit_multiplier", "value": a["limit_multiplier"]},
                 {"type": "TAG", "value": "node:" + lf["id"]}]}
            for i, (lf, path) in enumerate(rules(tree)) for a in [actions(lf)]]}],
        "defaultOutcome": {"decision": "REFER", "reason": "NO_RULE_MATCHED"}}
    return _finish(doc, backtest_summary)


def to_pega(tree, meta, column_types=None, backtest_summary=None):
    d, score = Pega(), meta.get("score_col", "score")
    doc = _header("Pega Customer Decision Hub", "Pegasystems", meta, "PEGA_DECISION_TABLE")
    doc["properties"] = [dict(i, property=d.ref(i["name"])) for i in _inputs(tree, meta, column_types)]
    doc["decisionTable"] = {
        "ruleName": "DT_" + se.safe_name(meta.get("name")), "appliesTo": "Data-Credit-Application",
        "evaluateAllRows": False,
        "returns": [".AdjustedScore", ".Decision", ".ReasonCodes", ".PricingTier", ".LimitMultiplier", ".StrategyNode"],
        "rows": [{"row": i + 1, "label": lf.get("name") or lf["id"], "when": d.when(path),
                  "set": {".AdjustedScore": d.score(d.ref(score), a),
                          ".Decision": d.decision(".AdjustedScore", a),
                          ".ReasonCodes": ";".join(a["reason_codes"]), ".PricingTier": a["pricing_tier"],
                          ".LimitMultiplier": a["limit_multiplier"], ".StrategyNode": lf["id"]}}
                 for i, (lf, path) in enumerate(rules(tree)) for a in [actions(lf)]],
        "otherwise": {".Decision": "REFER", ".ReasonCodes": "NO_ROW_MATCHED"}}
    return _finish(doc, backtest_summary)


def to_provenir(tree, meta, column_types=None, backtest_summary=None):
    score = meta.get("score_col", "score")

    def node(n):
        if n["type"] == "leaf":
            a = actions(n)
            return {"type": "OUTCOME", "id": n["id"], "label": n.get("name") or n["id"],
                    "scoreAdjustment": {"method": a["adjust"][0].upper(), "value": a["adjust"][1]},
                    "decision": ({"method": "SCORE_BANDS", "approveFrom": a["approve_at"], "referFrom": a["refer_at"],
                                  "else": "DECLINE", "missingScore": "REFER"} if a["mode"] == "cutoff"
                                 else {"method": "FIXED", "value": a["mode"].upper()}),
                    "reasonCodes": a["reason_codes"], "pricingTier": a["pricing_tier"],
                    "limitMultiplier": a["limit_multiplier"]}
        return {"type": "BRANCH", "id": n["id"], "label": n.get("name") or se.describe_condition(n),
                "attribute": n["variable"], "operator": se.IC_OPERATORS[n["op"]], "value": se._ic_value(n),
                "missingGoesTo": "MATCH" if n.get("missing") == "yes" else "NO_MATCH",
                "match": node(n["yes"]), "noMatch": node(n["no"])}

    doc = _header("Provenir", "Provenir", meta, "PROVENIR_DECISION_TREE")
    doc["dataModel"] = _inputs(tree, meta, column_types)
    doc["component"] = {"type": "DECISION_TREE", "name": meta.get("name"), "scoreAttribute": score, "root": node(tree)}
    return _finish(doc, backtest_summary)


def to_taktile(tree, meta, column_types=None, backtest_summary=None):
    d, score = Py(), meta.get("score_col", "score")
    doc = _header("Taktile", "Taktile", meta, "TAKTILE_DECISION_FLOW")
    doc["inputSchema"] = _inputs(tree, meta, column_types)
    doc["flow"] = {"nodes": [
        {"id": "segment", "type": "DECISION_TABLE", "hitPolicy": "FIRST",
         "rows": [{"if": d.when(path), "then": {"strategy_node": lf["id"]}} for lf, path in rules(tree)],
         "fallback": {"strategy_node": None}},
        {"id": "assign", "type": "SPLIT_BY", "field": "strategy_node", "branches": [
            {"value": lf["id"], "label": lf.get("name") or lf["id"], "assignments": {
                "adjusted_score": d.score(d.ref(score), a),
                "decision": d.decision("data.adjusted_score", a),
                "reason_codes": repr(a["reason_codes"]), "pricing_tier": repr(a["pricing_tier"]),
                "limit_multiplier": repr(a["limit_multiplier"])}}
            for lf, path in rules(tree) for a in [actions(lf)]],
         "otherwise": {"decision": "'REFER'", "reason_codes": "['NO_SEGMENT']"}}]}
    return _finish(doc, backtest_summary)


def to_dmn(tree, meta, column_types=None, backtest_summary=None):
    """DMN 1.3 decision table (FIRST hit policy). Each rule has one FEEL boolean input entry."""
    d, score = Feel(), meta.get("score_col", "score")
    name = se.safe_name(meta.get("name")) or "STRATEGY"
    outs = [("adjusted_score", "number"), ("decision", "string"), ("reason_codes", "string"),
            ("pricing_tier", "string"), ("limit_multiplier", "number"), ("strategy_node", "string")]
    x = lambda s: escape(str(s), {'"': "&quot;"})
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!-- Generated by Dataiku Strategy Studio. DMN 1.3 decision table; rule order = tree order (FIRST). -->',
             f'<definitions xmlns="https://www.omg.org/spec/DMN/20191111/MODEL/" id="def_{x(name)}" '
             f'name="{x(meta.get("name"))}" namespace="https://dataiku.com/strategy/{x(name)}">',
             f'  <decision id="dec_{x(name)}" name="{x(meta.get("name"))} v{x(meta.get("version", 1))}">',
             f'    <decisionTable id="dt_{x(name)}" hitPolicy="FIRST">',
             '      <input id="in_path" label="Path condition"><inputExpression typeRef="boolean">'
             '<text>true</text></inputExpression></input>']
    for i, (o, t) in enumerate(outs):
        lines.append(f'      <output id="out_{i}" name="{o}" typeRef="{t}"/>')
    for lf, path in rules(tree):
        a = actions(lf)
        adj = d.score(score, a)
        dec = d.decision("(" + adj + ")", a)
        vals = [adj, dec, d.lit(";".join(a["reason_codes"])), d.lit(a["pricing_tier"]) if a["pricing_tier"] else '""',
                f'{a["limit_multiplier"]:.12g}', d.lit(lf["id"])]
        lines.append(f'      <rule id="r_{x(lf["id"])}"><description>{x(lf.get("name") or lf["id"])}</description>')
        lines.append(f'        <inputEntry><text>{x(d.when(path))}</text></inputEntry>')
        lines += [f'        <outputEntry><text>{x(v)}</text></outputEntry>' for v in vals]
        lines.append('      </rule>')
    lines += ['    </decisionTable>', '  </decision>', '</definitions>', '']
    return "\n".join(lines)


EXPORTERS = {"oscilar": to_oscilar, "pega": to_pega, "provenir": to_provenir, "taktile": to_taktile, "dmn": to_dmn}


def export(fmt, tree, meta, column_types=None, backtest_summary=None):
    out = EXPORTERS[fmt](tree, meta, column_types, backtest_summary)
    return out if isinstance(out, str) else json.dumps(out, indent=2, default=str)
